
public class Exemplo003 {
    public static void main(String[] args) {
        double valor = 9.997;
        long valorLong = Math.round(valor);
        System.out.println(valorLong);
        int valorInt = Math.round(9.997f);
        System.out.println(valorInt);
        System.out.println(Math.log10(1000.0));
        System.out.println(Math.PI);
        System.out.println(Math.sqrt(16.0));
        System.out.println(Math.pow(2, 5)); //2**5
        System.out.println(Math.E);

    }   
}
